  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE CLIENTES ADD (ESTADO VARCHAR2(20) DEFAULT ''ACTIVO'' NOT NULL)'; END IF;

  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SOLICITUDES_ATENCION' AND COLUMN_NAME='FECHA_INICIO_ATENCION';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SOLICITUDES_ATENCION ADD (FECHA_INICIO_ATENCION TIMESTAMP)'; END IF;

  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SOLICITUDES_ATENCION' AND COLUMN_NAME='FECHA_FIN_ATENCION';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE SOLICITUDES_ATENCION ADD (FECHA_FIN_ATENCION TIMESTAMP)'; END IF;
END;
